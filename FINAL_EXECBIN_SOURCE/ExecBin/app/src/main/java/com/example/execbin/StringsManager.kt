package com.example.execbin

import android.content.Context

/**
 * Centralized localization manager for ExecBin.
 * All user-facing strings go through S.get("key") which returns
 * the translated string based on the current language preference.
 */
object S {
    private var currentLang = "en"

    fun init(context: Context) {
        val prefs = context.getSharedPreferences("app_lang_prefs", Context.MODE_PRIVATE)
        currentLang = prefs.getString("app_language", "en") ?: "en"
    }

    fun setLang(lang: String) {
        currentLang = lang
    }

    fun get(key: String): String {
        val langMap = translations[currentLang] ?: translations["en"]!!
        return langMap[key] ?: translations["en"]?.get(key) ?: key.replace("_", " ").replaceFirstChar { it.uppercaseChar() }
    }

    fun get(key: String, vararg args: Any): String {
        val template = get(key)
        return try {
            String.format(template, *args)
        } catch (e: Exception) {
            template
        }
    }

